/**
 * The ragù palette for the Raguverse frames, taken from `index.css`.
 *
 * The world and the lesson page run in frames of their own (an opaque origin,
 * a CSP, no access to ADE's stylesheet), and each used to carry a palette of its
 * own: slate greys and a blue accent, following the OS scheme (DS-25). Their
 * sheets now start with a block generated here from the values ADE draws with,
 * between `BEGIN` and `END`, and a test holds the blocks to what `index.css`
 * says. The frame's own variables (`--bg`, `--accent`…) read the `--ade-*` ones.
 * ADE tells the frame which scheme it is in (`data-theme` on its `<html>`, set
 * from the address), and the 3D city keeps its own colours.
 *
 * Rerun with `bun scripts/build-ragu-tokens.ts` after changing `index.css`.
 */

export const BEGIN = "/* ragu-tokens:begin (generated by scripts/build-ragu-tokens.ts from index.css; do not edit) */"
export const END = "/* ragu-tokens:end */"

/** The tokens that have a light and a dark value (`light-dark(a, b)`). */
export const SCHEME_TOKENS = [
  "bg",
  "sunken",
  "surface",
  "raised",
  "border",
  "border-strong",
  "text",
  "text-soft",
  "text-weak",
  "accent",
  "accent-fg",
  "working",
  "waiting",
  "done",
  "error",
  "ansi-magenta",
] as const

/** The tokens with one value in both schemes, copied as they are (some read the ones above). */
export const PLAIN_TOKENS = [
  "z-base",
  "state-work",
  "state-perm",
  "state-ask",
  "state-err",
  "state-limit",
  "radius-sm",
  "radius-md",
  "radius-lg",
  "radius-full",
  "weight-medium",
  "weight-semibold",
  "track-caps",
  "mono",
  "sans",
] as const

/** The text of a declaration `--ade-<name>: …;` in the shared block, up to its `;` outside any parenthesis. */
function declaration(css: string, name: string): string {
  const stripped = css.replace(/\/\*[\s\S]*?\*\//g, "")
  const matches = [...stripped.matchAll(new RegExp(`^\\s*--ade-${name}:`, "gm"))]
  // The last one is the shared block's: earlier ones belong to the glass theme's overrides.
  const found = matches.at(-1)
  if (!found) throw new Error(`--ade-${name} is not declared in index.css`)
  let i = found.index + found[0].length
  const from = i
  let depth = 0
  for (; i < stripped.length; i++) {
    const c = stripped[i]
    if (c === "(") depth++
    else if (c === ")") depth--
    else if (c === ";" && depth === 0) break
  }
  return stripped.slice(from, i).trim().replace(/\s+/g, " ")
}

/** Splits `light-dark(a, b)` into its two values, honouring nested parentheses. */
function pair(value: string): { light: string; dark: string } {
  const inner = /^light-dark\((.*)\)$/s.exec(value)?.[1]
  if (!inner) throw new Error(`not a light-dark() pair: ${value}`)
  let depth = 0
  for (let i = 0; i < inner.length; i++) {
    const c = inner[i]
    if (c === "(") depth++
    else if (c === ")") depth--
    else if (c === "," && depth === 0) return { light: inner.slice(0, i).trim(), dark: inner.slice(i + 1).trim() }
  }
  throw new Error(`no comma in light-dark(): ${value}`)
}

/** The block a frame's sheet starts with: dark by default, light under `data-theme="light"`. */
export function raguTokensBlock(indexCss: string): string {
  const pairs = SCHEME_TOKENS.map((name) => ({ name, ...pair(declaration(indexCss, name)) }))
  const lines = [
    BEGIN,
    ":root {",
    "  color-scheme: dark;",
    ...pairs.map(({ name, dark }) => `  --ade-${name}: ${dark};`),
    ...PLAIN_TOKENS.map((name) => `  --ade-${name}: ${declaration(indexCss, name)};`),
    "}",
    ':root[data-theme="light"] {',
    "  color-scheme: light;",
    ...pairs.map(({ name, light }) => `  --ade-${name}: ${light};`),
    "}",
    END,
  ]
  return lines.join("\n")
}

/** `sheet` with its generated block replaced by `block`, or put at the top if it has none. */
export function withBlock(sheet: string, block: string): string {
  const begin = sheet.indexOf(BEGIN)
  const end = sheet.indexOf(END)
  if (begin >= 0 && end > begin) return sheet.slice(0, begin) + block + sheet.slice(end + END.length)
  return `${block}\n\n${sheet}`
}
